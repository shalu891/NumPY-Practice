# Purpose: Understand NumPy and import the library

import numpy as np

# 1. Check NumPy version
print("NumPy version:", np.__version__)

# 2. Create a Python list
python_list = [10, 20, 30, 40, 50]
print("Python list:", python_list)
print("List type:", type(python_list))

# 3. Create a NumPy array
numpy_array = np.array([10, 20, 30, 40, 50])
print("NumPy array:", numpy_array)
print("Array type:", type(numpy_array))
